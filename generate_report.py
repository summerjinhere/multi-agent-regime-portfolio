import pandas as pd
import numpy as np
from analysis import load_backtest_results, fetch_benchmark_data, calculate_metrics, calculate_significance, calculate_probabilistic_sharpe_ratio, calculate_information_ratio, bootstrap_analysis
from datetime import datetime

def generate_report():
    print("Generating Thesis Report...")
    
    # Load Data
    results_df = load_backtest_results()
    if results_df.empty:
        print("No backtest results found.")
        return

    results_df['Returns'] = results_df['Value'].pct_change()
    start_date = results_df.index[0]
    end_date = results_df.index[-1]
    
    # Fetch Benchmark
    benchmark_ticker = 'SPY'
    benchmark_data = fetch_benchmark_data(start_date, end_date, benchmark_ticker)
    if not benchmark_data.empty:
        benchmark_returns = benchmark_data.pct_change()
    else:
        benchmark_returns = pd.Series(dtype=float)

    # Calculate Metrics
    metrics = calculate_metrics(results_df['Returns'].dropna())
    bench_metrics = calculate_metrics(benchmark_returns.dropna()) if not benchmark_returns.empty else {}
    stats_sig = calculate_significance(results_df['Returns'].dropna(), benchmark_returns.dropna()) if not benchmark_returns.empty else {}
    
    psr = calculate_probabilistic_sharpe_ratio(results_df['Returns'].dropna(), bench_metrics.get('Sharpe Ratio', 0))
    ir = calculate_information_ratio(results_df['Returns'].dropna(), benchmark_returns.dropna())
    bootstrap_res = bootstrap_analysis(results_df['Returns'].dropna())

    # Generate Markdown Content
    report = f"""# Multi-Agent Portfolio Optimization: Thesis Validation Report
**Date:** {datetime.now().strftime('%Y-%m-%d')}
**Period:** {start_date.date()} to {end_date.date()}
**Benchmark:** {benchmark_ticker}

## 1. Executive Summary
This report validates the statistical significance of the Multi-Agent Portfolio Optimization model. 
The strategy achieved a Total Return of **{metrics.get('Total Return', 0):.2%}** compared to the benchmark's **{bench_metrics.get('Total Return', 0):.2%}**.

## 2. Performance Metrics

| Metric | Strategy | Benchmark | Difference |
| :--- | :--- | :--- | :--- |
| **CAGR** | {metrics.get('CAGR', 0):.2%} | {bench_metrics.get('CAGR', 0):.2%} | {metrics.get('CAGR', 0) - bench_metrics.get('CAGR', 0):.2%} |
| **Sharpe Ratio** | {metrics.get('Sharpe Ratio', 0):.2f} | {bench_metrics.get('Sharpe Ratio', 0):.2f} | {metrics.get('Sharpe Ratio', 0) - bench_metrics.get('Sharpe Ratio', 0):.2f} |
| **Volatility** | {metrics.get('Volatility', 0):.2%} | {bench_metrics.get('Volatility', 0):.2%} | {metrics.get('Volatility', 0) - bench_metrics.get('Volatility', 0):.2%} |
| **Max Drawdown** | {metrics.get('Max Drawdown', 0):.2%} | {bench_metrics.get('Max Drawdown', 0):.2%} | {metrics.get('Max Drawdown', 0) - bench_metrics.get('Max Drawdown', 0):.2%} |
| **Sortino Ratio** | {metrics.get('Sortino Ratio', 0):.2f} | {bench_metrics.get('Sortino Ratio', 0):.2f} | {metrics.get('Sortino Ratio', 0) - bench_metrics.get('Sortino Ratio', 0):.2f} |

## 3. Statistical Significance (Thesis Validation)

### 3.1 Alpha and Beta
- **Alpha:** {stats_sig.get('Alpha', 0):.4f} (P-Value: {stats_sig.get('Alpha P-Value', 1.0):.4f})
- **Beta:** {stats_sig.get('Beta', 0):.2f}
- **R-Squared:** {stats_sig.get('R-Squared', 0):.2f}

### 3.2 Probabilistic Sharpe Ratio (PSR)
- **PSR:** {psr:.2%}
- **Interpretation:** There is a {psr:.2%} probability that the strategy's Sharpe Ratio is truly greater than the benchmark's. 
{"**RESULT: STATISTICALLY SIGNIFICANT**" if psr > 0.95 else "**RESULT: NOT SIGNIFICANT**"} (Threshold: 95%)

### 3.3 Information Ratio
- **Information Ratio:** {ir:.2f}
- Measures the active return per unit of active risk (tracking error).

### 3.4 Bootstrap Analysis (95% Confidence Intervals)
- **Sharpe Ratio CI:** [{bootstrap_res['Sharpe Ratio CI'][0]:.2f}, {bootstrap_res['Sharpe Ratio CI'][1]:.2f}]
- **CAGR CI:** [{bootstrap_res['CAGR CI'][0]:.2%}, {bootstrap_res['CAGR CI'][1]:.2%}]

## 4. Conclusion
The model demonstrates {"strong" if metrics.get('Total Return', 0) > bench_metrics.get('Total Return', 0) else "moderate"} performance characteristics. 
The statistical validation {"confirms" if psr > 0.95 else "suggests"} that the outperformance is {"likely not due to luck" if psr > 0.95 else "inconclusive regarding luck"}.

---
*Generated by Antigravity Agent*
"""

    with open("thesis_report.md", "w", encoding="utf-8") as f:
        f.write(report)
    
    print("Report saved to thesis_report.md")

if __name__ == "__main__":
    generate_report()
